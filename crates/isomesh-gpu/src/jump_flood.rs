//! Jump flooding: a distance field in `O(log n)` passes, on the GPU.
//!
//! Ticket: S-005. Rong & Tan, *Jump flooding in GPU with applications to Voronoi
//! diagram and distance transform*, I3D 2006 (`10.1145/1111411.1111431`).
//!
//! # What it is, and what "approximate" costs here
//!
//! Every sample carries the nearest surface point it has heard about. The seed
//! pass puts a crossing on each sample adjacent to a sign change; then
//! `⌈log₂ n⌉` passes let each sample look at 26 neighbours a halving stride
//! away and adopt the better seed. `n/2, n/4, … 1` — so a 65³ grid is six
//! dispatches rather than the 65 a naive propagation would need.
//!
//! **It is not exact, and the word is a measurement here rather than an
//! adjective.** A sample only ever sees seeds sitting at one of 27 fixed offsets
//! at each stride, so a Voronoi region whose owner never lands on that lattice
//! is missed.
//!
//! # What the measurement actually found (M-257)
//!
//! The approximate GPU method is **more accurate than both exact CPU
//! constructors**, on every one of the twelve rows — four exact reference fields
//! at 17³, 33³ and 65³. Worst error against the analytic field:
//!
//! | field | n | jump flood | swept (S-002) | exact transform (S-001) |
//! |---|---|---|---|---|
//! | `sphere` | 65 | **0.02048** | 0.09271 | 0.06250 |
//! | `torus` | 65 | **0.02370** | 0.10527 | 0.06233 |
//! | `box_exact` | 65 | **0.08839** | 0.15861 | 0.10825 |
//! | `thin_plate` | 65 | **0.06250** | 0.19221 | 0.08927 |
//!
//! Full table: `docs/measurements/jump_flood.csv`, regenerated by
//! `cargo test -p isomesh-gpu jump_flood -- --nocapture`.
//!
//! That is not a paradox. "Exact" in S-001 means exact to the nearest *sample*,
//! which quantises every distance to the grid; the sweep is exact in the limit
//! but its Godunov update is first-order. The flood is seeded sub-cell and then
//! measures a true Euclidean distance to that seed, so on these fields the
//! seeding buys more than the lattice restriction costs.
//!
//! **This makes "error against S-001" the wrong assertion**, and it was written
//! twice before that was clear. Asserting the flood agrees with a CPU
//! constructor asserts it reproduce that constructor's error: `thin_plate` at
//! 17³ misses a half-cell agreement bound at 0.523 cells while being the most
//! accurate of the three. The gate is against the analytic field.
//!
//! # Seeded from the crossing, not from the sample
//!
//! The textbook seeds each boundary sample with **its own position**, which
//! quantises every distance to the grid and floors the error at half a cell.
//! That would make any comparison against S-001 a comparison of seedings. This
//! seeds the linearly interpolated crossing on each cut edge — the same sub-cell
//! information the CPU's swept and marched constructors use — so what the
//! comparison isolates is the flood's own approximation.
//!
//! ```no_run
//! use isomesh::fields::Sphere;
//! use isomesh_gpu::{FieldBuffer, GridParams, JumpFlood, headless};
//!
//! # fn main() -> Result<(), Box<dyn std::error::Error>> {
//! let gpu = headless::Gpu::new()?;
//! let grid = GridParams::new([65; 3], [-2.0; 3], 0.0625)?;
//! let field = FieldBuffer::sampled(gpu.device(), gpu.queue(), grid, &Sphere::<f32>::canonical())?;
//!
//! let flood = JumpFlood::new(gpu.device())?;
//! let distance = flood.build(gpu.device(), gpu.queue(), &field)?;
//! # let _ = distance;
//! # Ok(())
//! # }
//! ```

